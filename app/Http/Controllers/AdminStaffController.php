<?php

namespace App\Http\Controllers;

use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\Hash;
use App\Models\User;
use App\Models\Manager;
use App\Models\Receptionist;
use App\Models\Trainer;
use App\Models\StaffLog;
use App\Models\AdminPasswordResetRequest;
use Illuminate\Support\Facades\Password;
class AdminStaffController extends Controller
{
    /**
     * Kirim email verifikasi dengan aman: kalau server email (SMTP) sedang
     * tidak terhubung, alur pembuatan akun TIDAK boleh gagal (500).
     * Kegagalan dicatat ke log dan dikembalikan sebagai false supaya
     * controller bisa memberi tahu admin untuk kirim ulang nanti.
     */
    private function sendVerificationEmailSafely(User $staff): bool
    {
        try {
            $staff->sendEmailVerificationNotification();
            return true;
        } catch (\Throwable $e) {
            report($e);
            return false;
        }
    }

    public function index()
    {
        $user = Auth::user();
        $tenant = $user->tenant;

        $staffs = User::with('latestPendingPasswordReset')
            ->where('tenant_id', $tenant->id)
            ->whereIn('role', ['admin', 'manager', 'owner'])
            ->latest()
            ->get();

        return view('admin.staff.index', compact('staffs', 'tenant'));
    }

    public function store(Request $request)
    {
        $user = Auth::user();
        if ($user->isOwner()) {
            return redirect()->back()->with('error', 'Mode Pemantauan Owner: Anda hanya memiliki hak akses untuk melihat data.');
        }
        $tenant = $user->tenant;

        $request->validate([
            'name' => 'required|string|max:255',
            'email' => 'required|email|unique:users,email',
            'password' => 'nullable|string|min:4',
            'role' => 'required|string|in:manager,owner',
            'phone' => 'nullable|string|max:20',
        ], [
            'name.required'  => 'Nama staf wajib diisi.',
            'email.required' => 'Email login wajib diisi.',
            'email.email'    => 'Format email tidak valid.',
            'email.unique'   => 'Email ini sudah terdaftar, gunakan email lain.',
            'password.min'   => 'Password minimal 4 karakter.',
            'role.required'  => 'Role / jabatan wajib dipilih.',
            'role.in'        => 'Admin hanya dapat mendaftarkan akun Manager Gym dan Owner.',
        ]);

        if ($tenant && !$tenant->canAddStaff()) {
            $maxStaff = $tenant->maxStaff();
            return redirect()->back()->with('error', "Gagal menambahkan akun staf: Kuota maksimal karyawan untuk {$tenant->plan_name} ({$maxStaff} Akun Karyawan) telah tercapai. Silakan lakukan upgrade paket.");
        }

        if ($tenant && !$tenant->isStaffRoleAllowed($request->role)) {
            return redirect()->back()->with('error', "Paket {$tenant->plan_name} tidak mengizinkan role {$request->role}. Silakan upgrade paket langganan.");
        }

        // Jika password kosong → generate password default otomatis
        $autoGenerated = false;
        if (empty($request->password)) {
            $rawPassword = 'PetGym-' . strtoupper(substr(md5(uniqid(mt_rand(), true)), 0, 8));
            $autoGenerated = true;
        } else {
            $rawPassword = $request->password;
        }

        $staff = User::create([
            'tenant_id' => $tenant->id,
            'name' => $request->name,
            'email' => $request->email,
            'password' => Hash::make($rawPassword),
            'role' => $request->role,
            'must_change_password' => true,
        ]);

        // Auto Sync ke tabel profil dedicated jika role manager
        if ($staff->role === 'manager') {
            Manager::updateOrCreate(
                ['tenant_id' => $tenant->id, 'user_id' => $staff->id],
                ['name' => $staff->name, 'email' => $staff->email, 'department' => 'Operasional', 'status' => 'active']
            );
        }

        // Auto Sync ke data Tenant jika role owner
        if ($staff->role === 'owner' && $tenant) {
            $tenant->update([
                'owner_name' => $staff->name,
                'owner_email' => $staff->email,
            ]);
        }

        StaffLog::create([
            'tenant_id' => $tenant->id,
            'user_id' => $user->id,
            'action' => 'Tambah Akun Pengelola',
            'description' => "Mendaftarkan akun pengelola baru: {$staff->name} ({$staff->email}) sebagai {$staff->role}",
            'ip_address' => $request->ip(),
        ]);

        // Akun staf baru WAJIB verifikasi email dulu sebelum bisa login ke dashboard.
        // Kalau server email sedang mati, akun TETAP tersimpan — admin tinggal
        // pakai tombol "Kirim Verifikasi" nanti (email gagal TIDAK menggagalkan akun).
        $emailSent = $this->sendVerificationEmailSafely($staff);

        if (!$emailSent) {
            return redirect()->route('admin.staff.index')->with('warning', "Akun staf {$staff->name} berhasil dibuat, TETAPI email verifikasi gagal terkirim (server email tidak terhubung). Gunakan tombol 'Kirim Verifikasi' di daftar staf setelah server email aktif.");
        }

        return redirect()->route('admin.staff.index')->with('success', "Akun staf {$staff->name} berhasil dibuat. Link verifikasi email telah dikirim ke {$staff->email} — staf harus memverifikasi emailnya sebelum bisa login.");
    }

    /**
     * Mengirim ulang link verifikasi email untuk akun staf yang belum verifikasi.
     */
    public function sendVerification(Request $request, $id)
    {
        $user = Auth::user();
        $tenant = $user->tenant;

        $staff = User::where('tenant_id', $tenant->id)->findOrFail($id);

        if ($user->isAdmin() && !in_array($staff->role, ['manager', 'owner'])) {
            return redirect()->route('admin.staff.index')->with('error', 'Admin hanya dapat mengelola akun Manager Gym dan Owner.');
        }

        if ($user->isManager() && !in_array($staff->role, ['receptionist', 'trainer'])) {
            return redirect()->route('admin.staff.index')->with('error', 'Manager Gym hanya dapat mengelola akun Resepsionis dan Personal Trainer.');
        }

        if ($staff->hasVerifiedEmail()) {
            return redirect()->route('admin.staff.index')->with('success', "Email akun {$staff->name} sudah terverifikasi.");
        }

        $emailSent = $this->sendVerificationEmailSafely($staff);

        StaffLog::create([
            'tenant_id' => $tenant->id,
            'user_id' => $user->id,
            'action' => 'Kirim Ulang Verifikasi Email',
            'description' => "Mengirim ulang link verifikasi email untuk akun staf {$staff->name}",
            'ip_address' => $request->ip(),
        ]);

        if (!$emailSent) {
            return redirect()->route('admin.staff.index')->with('error', "Link verifikasi email GAGAL dikirim ke {$staff->email} (server email tidak terhubung). Coba lagi setelah server email aktif.");
        }

        return redirect()->route('admin.staff.index')->with('success', "Link verifikasi email telah dikirim ulang ke {$staff->email}.");
    }

    public function destroy(Request $request, $id)
    {
        $user = Auth::user();
        $tenant = $user->tenant;

        if ($user->id == $id) {
            return redirect()->route('admin.staff.index')->with('error', 'Anda tidak dapat menghapus akun Anda sendiri.');
        }

        $staff = User::where('tenant_id', $tenant->id)->findOrFail($id);
        
        if ($user->isAdmin() && !in_array($staff->role, ['manager', 'owner'])) {
            return redirect()->route('admin.staff.index')->with('error', 'Admin hanya dapat mengelola akun Manager Gym dan Owner.');
        }

        if ($user->isManager() && !in_array($staff->role, ['receptionist', 'trainer'])) {
            return redirect()->route('admin.staff.index')->with('error', 'Manager Gym hanya dapat mengelola akun Resepsionis dan Personal Trainer.');
        }

        $staffName = $staff->name;

        // Clean up role profile records
        Manager::where('user_id', $staff->id)->delete();
        Receptionist::where('user_id', $staff->id)->delete();
        Trainer::where('user_id', $staff->id)->delete();

        $staff->delete();

        StaffLog::create([
            'tenant_id' => $tenant->id,
            'user_id' => $user->id,
            'action' => 'Hapus Akun Staf',
            'description' => "Menghapus akun staf {$staffName}",
            'ip_address' => $request->ip(),
        ]);

        return redirect()->route('admin.staff.index')->with('success', "Akun staf {$staffName} berhasil dihapus.");
    }

    public function toggleStatus(Request $request, $id)
    {
        $user = Auth::user();
        if ($user->isOwner()) {
            return redirect()->back()->with('error', 'Mode Pemantauan Owner: Anda hanya memiliki hak akses untuk melihat data.');
        }
        $tenant = $user->tenant;

        if ($user->id == $id) {
            return redirect()->route('admin.staff.index')->with('error', 'Anda tidak dapat menonaktifkan akun Anda sendiri.');
        }

        $staff = User::where('tenant_id', $tenant->id)->findOrFail($id);

        if (!in_array($staff->role, ['manager', 'owner'])) {
            return redirect()->route('admin.staff.index')->with('error', 'Admin hanya dapat mengatur status akun Manager dan Owner.');
        }

        $newStatus = !$staff->isActive();
        $staff->update(['is_active' => $newStatus]);

        $statusText = $newStatus ? 'diaktifkan kembali' : 'dinonaktifkan';

        StaffLog::create([
            'tenant_id' => $tenant->id,
            'user_id' => $user->id,
            'action' => $newStatus ? 'Aktivasi Akun Staf' : 'Nonaktifkan Akun Staf',
            'description' => "Admin {$user->name} mengubah status akun {$staff->name} ({$staff->role}) menjadi {$statusText}.",
            'ip_address' => $request->ip(),
        ]);

        return redirect()->route('admin.staff.index')->with('success', "Akun {$staff->name} berhasil {$statusText}.");
    }

    /**
     * Tampilkan Halaman Permohonan Reset Password Staf & Member Gym (Approval Admin).
     */
    public function passwordResets(Request $request)
    {
        $user = Auth::user();
        $tenant = $user->tenant;

        if (!$tenant) {
            return redirect()->route('admin.dashboard')->with('error', 'Data gym Anda tidak ditemukan.');
        }

        $query = AdminPasswordResetRequest::with(['user', 'approver'])
            ->where('tenant_id', $tenant->id)
            ->where('target_type', 'admin');

        if ($request->filled('status') && $request->query('status') !== 'all') {
            $query->where('status', $request->query('status'));
        }

        if ($request->filled('search')) {
            $search = $request->query('search');
            $query->where(function ($q) use ($search) {
                $q->where('email', 'like', "%{$search}%")
                  ->orWhere('admin_name', 'like', "%{$search}%")
                  ->orWhere('user_role', 'like', "%{$search}%");
            });
        }

        $requests = $query->latest('id')->paginate(15)->withQueryString();
        $pendingCount = AdminPasswordResetRequest::where('tenant_id', $tenant->id)
            ->where('target_type', 'admin')
            ->where('status', 'pending')
            ->count();

        return view('admin.staff.password-resets', compact('requests', 'pendingCount', 'tenant'));
    }

    /**
     * Setujui Permohonan Reset Password Staf / Member dan Kirim Tautan Reset ke Email.
     */
    public function approvePasswordReset(Request $request, $id)
    {
        $admin = Auth::user();
        $tenant = $admin->tenant;

        $resetReq = AdminPasswordResetRequest::where('tenant_id', $tenant->id)
            ->where('target_type', 'admin')
            ->findOrFail($id);

        if ($resetReq->status !== 'pending') {
            return redirect()->back()->with('error', 'Permohonan reset password ini sudah pernah diproses sebelumnya.');
        }

        $user = $resetReq->user;
        if (!$user) {
            return redirect()->back()->with('error', 'Data pengguna tidak ditemukan.');
        }

        try {
            $status = Password::sendResetLink(['email' => $user->email]);
        } catch (\Throwable $e) {
            report($e);
            return redirect()->back()->with('error', 'Gagal mengirim email tautan reset password. Periksa koneksi SMTP server email.');
        }

        $resetReq->update([
            'status'           => 'approved',
            'approved_by'      => $admin->id,
            'approved_at'      => now(),
            'token_expires_at' => now()->addMinutes(60),
            'notes'            => $request->notes,
        ]);

        StaffLog::create([
            'tenant_id'   => $tenant->id,
            'user_id'     => $admin->id,
            'action'      => 'Approve Reset Password Pengguna',
            'description' => "Admin {$admin->name} menyetujui permohonan reset password untuk {$user->name} ({$user->role} - {$user->email}). Tautan reset dikirim ke email.",
            'ip_address'  => $request->ip(),
        ]);

        return redirect()->back()->with('success', "Permohonan reset password untuk {$user->name} ({$user->email}) berhasil disetujui! Tautan pembuatan kata sandi baru telah dikirimkan ke email.");
    }

    /**
     * Tolak Permohonan Reset Password Staf / Member Gym.
     */
    public function rejectPasswordReset(Request $request, $id)
    {
        $admin = Auth::user();
        $tenant = $admin->tenant;

        $resetReq = AdminPasswordResetRequest::where('tenant_id', $tenant->id)
            ->where('target_type', 'admin')
            ->findOrFail($id);

        if ($resetReq->status !== 'pending') {
            return redirect()->back()->with('error', 'Permohonan reset password ini sudah pernah diproses sebelumnya.');
        }

        $resetReq->update([
            'status'      => 'rejected',
            'approved_by' => $admin->id,
            'approved_at' => now(),
            'notes'       => $request->notes ?: 'Ditolak oleh Admin Gym.',
        ]);

        StaffLog::create([
            'tenant_id'   => $tenant->id,
            'user_id'     => $admin->id,
            'action'      => 'Tolak Reset Password Pengguna',
            'description' => "Admin {$admin->name} menolak permohonan reset password untuk {$resetReq->admin_name} ({$resetReq->email}).",
            'ip_address'  => $request->ip(),
        ]);

        return redirect()->back()->with('success', "Permohonan reset password untuk '{$resetReq->admin_name}' berhasil ditolak.");
    }
}